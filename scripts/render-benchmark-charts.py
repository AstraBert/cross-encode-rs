BENCH_LABELS = {
    "cross-encode-rs.txt": "cross-encode-rs",
    "fastembed-py.txt": "fastembed",
    "sentence-transformers-py.txt": "sentence-transformers",
}
PERCENTILES = ["min", "p50", "p90", "p99", "max"]

DURATION_UNITS = {"ns": 1e-6, "µs": 1e-3, "us": 1e-3, "ms": 1.0, "s": 1e3}
DURATION_RE = re.compile(r"([0-9.]+)\s*(ns|µs|us|ms|s)\b")


def parse_duration_ms(text: str) -> float:
    m = DURATION_RE.search(text)
    if not m:
        raise ValueError(f"could not parse duration from {text!r}")
    value, unit = m.groups()
    return float(value) * DURATION_UNITS[unit]


def parse_benchmark_file(path: Path) -> dict[str, dict[str, float]]:
    """Returns {section_name: {percentile: value}}, values in ms for latency
    sections and raw counts for the document-count section."""
    text = path.read_text()
    sections: dict[str, dict[str, float]] = {}
    current = None
    for line in text.splitlines():
        line = line.strip()
        if not line:
            continue
        section_match = re.match(
            r"^(Documents per entry|Per-request latency|Per-document latency)", line
        )
        if section_match:
            current = section_match.group(1)
            sections[current] = {}
            continue
        pct_match = re.match(r"^(min|p50|p90|p99|max):\s*(.+)$", line)
        if pct_match and current:
            key, raw = pct_match.groups()
            if current == "Documents per entry":
                sections[current][key] = float(raw)
            else:
                sections[current][key] = parse_duration_ms(raw)
    return sections


def render_benchmarks_page() -> None:
    results_dir = REPO_ROOT / "crates" / "benchmarks" / "results"
    files = {
        BENCH_LABELS[p.name]: parse_benchmark_file(p)
        for p in results_dir.glob("*.txt")
        if p.name in BENCH_LABELS
    }
    if not files:
        print(f"no benchmark .txt files found in {results_dir}, skipping")
        return

    series_names = [
        s
        for s in ("cross-encode-rs", "fastembed", "sentence-transformers")
        if s in files
    ]

    body = ""
    for section, title, fmt in [
        (
            "Per-request latency",
            "Per-request latency (ms, lower is better)",
            lambda v: f"{v:.2f} ms",
        ),
        (
            "Per-document latency",
            "Per-document latency (ms, lower is better)",
            lambda v: f"{v:.3f} ms",
        ),
    ]:
        values = {s: [files[s][section][p] for p in PERCENTILES] for s in series_names}
        body += chart_section(
            title, PERCENTILES, series_names, values, fmt, "percentile"
        )

    html = page_shell(
        "cross-encode-rs benchmark results",
        "Rerank latency across the cross-encode-rs (Rust/ONNX), fastembed, and sentence-transformers "
        "(ONNX backend) libraries, run over the same dataset.",
        body,
    )
    out_dir = REPO_ROOT / "pages" / "benchmarks"
    out_dir.mkdir(parents=True, exist_ok=True)
    out_path = out_dir / "index.html"
    out_path.write_text(html)
    print(f"wrote {out_path}")



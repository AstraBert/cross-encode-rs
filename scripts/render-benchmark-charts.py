LOAD_TEST_LABELS = {
    "cross-encode-rs": "cross-encode-rs",
    "fastembed": "fastembed",
    "sentence-transformers": "sentence-transformers",
}


@dataclass
class LoadTestRun:
    total_requests: int
    avg_response_ms: float
    requests_per_sec: float


def parse_load_test_file(path: Path) -> list[LoadTestRun]:
    text = path.read_text()
    blocks = re.split(r"(?=Total requests:)", text)
    runs = []
    for block in blocks:
        if not block.strip():
            continue
        total = re.search(r"Total requests:\s*(\d+)", block)
        avg = re.search(r"Average response time:\s*([\d.]+)\s*ms", block)
        rps = re.search(r"Requests per second:\s*([\d.]+)", block)
        if not (total and avg and rps):
            continue
        runs.append(
            LoadTestRun(
                total_requests=int(total.group(1)),
                avg_response_ms=float(avg.group(1)),
                requests_per_sec=float(rps.group(1)),
            )
        )
    return runs


def render_load_test_page() -> None:
    results_dir = REPO_ROOT / "load-test" / "results"
    per_system_runs: dict[str, list[LoadTestRun]] = {}
    for system_dir in results_dir.iterdir():
        if not system_dir.is_dir() or system_dir.name not in LOAD_TEST_LABELS:
            continue
        runs: list[LoadTestRun] = []
        for f in sorted(system_dir.glob("*.txt")):
            runs.extend(parse_load_test_file(f))
        if runs:
            per_system_runs[system_dir.name] = runs

    if not per_system_runs:
        print(f"no load-test result files found in {results_dir}, skipping")
        return

    series_names = [
        s
        for s in ("cross-encode-rs", "fastembed", "sentence-transformers")
        if s in per_system_runs
    ]

    # bucket by request count, average across repeated runs
    buckets = sorted(
        {r.total_requests for runs in per_system_runs.values() for r in runs}
    )
    group_labels = [f"{b:,} requests" for b in buckets]

    def averaged(field: str) -> dict[str, list[float]]:
        out: dict[str, list[float]] = {}
        for s in series_names:
            row = []
            for b in buckets:
                matching = [
                    getattr(r, field)
                    for r in per_system_runs[s]
                    if r.total_requests == b
                ]
                row.append(sum(matching) / len(matching) if matching else 0.0)
            out[s] = row
        return out

    n_runs = {
        s: len({r.total_requests for r in per_system_runs[s]}) for s in series_names
    }
    run_counts = {s: len(per_system_runs[s]) // max(n_runs[s], 1) for s in series_names}
    note = (
        "Averaged across "
        + ", ".join(f"{s}: {run_counts[s]} run(s)" for s in series_names)
        + " per request count."
    )

    body = ""
    body += chart_section(
        "Average response time (ms, lower is better)",
        group_labels,
        series_names,
        averaged("avg_response_ms"),
        lambda v: f"{v:.0f} ms",
        "load",
        note,
    )
    body += chart_section(
        "Throughput (requests/sec, higher is better)",
        group_labels,
        series_names,
        averaged("requests_per_sec"),
        lambda v: f"{v:.1f} req/s",
        "load",
        note,
    )

    html = page_shell(
        "cross-encode-rs load test results",
        "Concurrent-request load test (load-test/main.go) against the Rust server and the Python "
        "reference servers, at 1,000 and 10,000 requests.",
        body,
    )
    out_dir = REPO_ROOT / "pages" / "load-test"
    out_dir.mkdir(parents=True, exist_ok=True)
    out_path = out_dir / "index.html"
    out_path.write_text(html)
    print(f"wrote {out_path}")


def render_index_page() -> None:
    body = """  <ul class="index-list">
    <li><a href="benchmarks/">Benchmark results</a> — rerank latency, cross-encode-rs vs fastembed vs sentence-transformers</li>
    <li><a href="load-test/">Load test results</a> — response time and throughput under concurrent load</li>
  </ul>
"""
    html = page_shell(
        "cross-encode-rs results",
        "Static benchmark and load-test reports for cross-encode-rs.",
        body,
        back_link="",
    )
    out_dir = REPO_ROOT / "pages"
    out_dir.mkdir(parents=True, exist_ok=True)
    out_path = out_dir / "index.html"
    out_path.write_text(html)
    print(f"wrote {out_path}")


if __name__ == "__main__":
    render_benchmarks_page()
    render_load_test_page()
    render_index_page()

BENCH_LABELS = {
    "cross-encode-rs.txt": "cross-encode-rs",
    "fastembed-py.txt": "fastembed",
    "sentence-transformers-py.txt": "sentence-transformers",
}
# results/<dir>/ -> model shown on the page; unknown dirs fall back to the dir name
BENCH_MODEL_LABELS = {
    "xenova": "Xenova/ms-marco-MiniLM-L-6-v2",
}
PERCENTILES = ["min", "p50", "p90", "p99", "max"]

DURATION_UNITS = {"ns": 1e-6, "µs": 1e-3, "us": 1e-3, "ms": 1.0, "s": 1e3}
DURATION_RE = re.compile(r"([0-9.]+)\s*(ns|µs|us|ms|s)\b")


def parse_duration_ms(text: str) -> float:
    m = DURATION_RE.search(text)
    if not m:
        raise ValueError(f"could not parse duration from {text!r}")
    value, unit = m.groups()
    return float(value) * DURATION_UNITS[unit]


def parse_benchmark_file(path: Path) -> dict[str, dict[str, float]]:
    """Returns {section_name: {percentile: value}}, values in ms for latency
    sections and raw counts for the document-count section."""
    text = path.read_text()
    sections: dict[str, dict[str, float]] = {}
    current = None
    for line in text.splitlines():
        line = line.strip()
        if not line:
            continue
        section_match = re.match(
            r"^(Documents per entry|Per-request latency|Per-document latency)", line
        )
        if section_match:
            current = section_match.group(1)
            sections[current] = {}
            continue
        pct_match = re.match(r"^(min|p50|p90|p99|max):\s*(.+)$", line)
        if pct_match and current:
            key, raw = pct_match.groups()
            if current == "Documents per entry":
                sections[current][key] = float(raw)
            else:
                sections[current][key] = parse_duration_ms(raw)
    return sections


# results/load-time-<dir>.json, written by scripts/model-load-time-bench.sh
LOAD_TIME_ORDER = ["xenova", "jina"]  # small model first
LOAD_TIME_SHORT_LABELS = {
    "xenova": "MiniLM-L-6-v2",
    "jina": "jina-reranker-v2",
}


def load_time_series(command: str) -> str:
    if command.startswith("./target/release/benchmarks"):
        return "cross-encode-rs"
    if "--st-model" in command:
        return "sentence-transformers"
    return "fastembed"


def parse_load_time_file(path: Path) -> dict[str, tuple[float, float]]:
    """Returns {series: (mean_ms, stddev_ms)} from a hyperfine JSON export.
    hyperfine's memory_usage_byte is left out on purpose: it is the peak RSS
    across all of hyperfine's children so far, not per command."""
    import json

    out = {}
    for r in json.loads(path.read_text())["results"]:
        out[load_time_series(r["command"])] = (r["mean"] * 1e3, r["stddev"] * 1e3)
    return out


def human_join(items: list[str]) -> str:
    if len(items) <= 2:
        return " and ".join(items)
    return ", ".join(items[:-1]) + ", and " + items[-1]


def render_benchmarks_page() -> None:
    results_dir = REPO_ROOT / "crates" / "benchmarks" / "results"
    # one subdirectory per model, e.g. results/xenova/*.txt, results/jina/*.txt
    per_model: dict[str, dict[str, dict[str, dict[str, float]]]] = {}
    for model_dir in sorted(p for p in results_dir.iterdir() if p.is_dir()):
        files = {
            BENCH_LABELS[p.name]: parse_benchmark_file(p)
            for p in model_dir.glob("*.txt")
            if p.name in BENCH_LABELS
        }
        if files:
            per_model[model_dir.name] = files
    if not per_model:
        print(f"no benchmark .txt files found under {results_dir}/*/, skipping")
        return

    all_series: set[str] = set()
    blog_charts: dict[str, str] = {}
    body = ""
    for model, files in per_model.items():
        series_names = [
            s
            for s in ("cross-encode-rs", "fastembed", "sentence-transformers")
            if s in files
        ]
        all_series.update(series_names)
        model_label = BENCH_MODEL_LABELS.get(model, model)
        for section, slug, title, x_title, fmt in [
            (
                "Per-request latency",
                "per-request",
                "Per-request latency (ms, lower is better)",
                "per-request latency, ms (lower is better)",
                lambda v: f"{v:.2f} ms",
            ),
            (
                "Per-document latency",
                "per-document",
                "Per-document latency (ms, lower is better)",
                "per-document latency, ms (lower is better)",
                None,
            ),
        ]:
            values = {
                s: [files[s][section][p] for p in PERCENTILES] for s in series_names
            }
            if fmt is None:
                # sub-millisecond charts need the third decimal, slower ones don't
                decimals = 3 if max(v for vs in values.values() for v in vs) < 5 else 2
                fmt = lambda v, d=decimals: f"{v:.{d}f} ms"
            body += chart_section(
                f"{model_label}: {title}",
                PERCENTILES,
                series_names,
                values,
                fmt,
                "percentile",
                x_title,
            )
            blog_charts[f"{model}-{slug}.html"] = standalone_chart_page(
                f"{model_label}: {title}",
                chart_body(
                    PERCENTILES, series_names, values, fmt, x_title, "percentile"
                ),
            )

    # model load time (process start to model ready), one group per model
    load_times = {
        m: parse_load_time_file(results_dir / f"load-time-{m}.json")
        for m in LOAD_TIME_ORDER
        if (results_dir / f"load-time-{m}.json").exists()
    }
    if load_times:
        lt_series = [
            s
            for s in ("cross-encode-rs", "fastembed", "sentence-transformers")
            if all(s in lt for lt in load_times.values())
        ]
        lt_groups = [LOAD_TIME_SHORT_LABELS.get(m, m) for m in load_times]
        lt_values = {s: [lt[s][0] for lt in load_times.values()] for s in lt_series}
        lt_labels = {
            s: [f"{lt[s][0]:.0f} ± {lt[s][1]:.0f} ms" for lt in load_times.values()]
            for s in lt_series
        }
        lt_x_title = "model load time, ms (mean ± stddev, lower is better)"
        lt_fmt = lambda v: f"{v:.0f} ms"
        body += chart_section(
            "Model load time (ms, lower is better)",
            lt_groups,
            lt_series,
            lt_values,
            lt_fmt,
            "model",
            lt_x_title,
            "Wall-clock time of a process that loads the model and exits, measured with "
            "hyperfine (10 warmup runs, 40 measured runs). For Python this includes "
            "interpreter startup and imports.",
            lt_labels,
        )
        blog_charts["load-time.html"] = standalone_chart_page(
            "Model load time",
            chart_body(
                lt_groups, lt_series, lt_values, lt_fmt, lt_x_title, "model", lt_labels
            ),
        )

    library_desc = {
        "cross-encode-rs": "cross-encode-rs (Rust/ONNX)",
        "fastembed": "fastembed",
        "sentence-transformers": "sentence-transformers (ONNX backend)",
    }
    libraries = [
        library_desc[s]
        for s in ("cross-encode-rs", "fastembed", "sentence-transformers")
        if s in all_series
    ]
    models = [BENCH_MODEL_LABELS.get(m, m) for m in per_model]
    html = page_shell(
        "cross-encode-rs benchmark results",
        f"Rerank latency across the {human_join(libraries)} libraries, run over the same "
        f"dataset, for {human_join(models)}.",
        body,
    )
    out_dir = REPO_ROOT / "pages" / "benchmarks"
    out_dir.mkdir(parents=True, exist_ok=True)
    out_path = out_dir / "index.html"
    out_path.write_text(html)
    print(f"wrote {out_path}")

    # one self-contained file per chart, framed for screenshotting into the blog
    blog_dir = REPO_ROOT / "pages" / "blog"
    blog_dir.mkdir(parents=True, exist_ok=True)
    for name, chart_html in blog_charts.items():
        (blog_dir / name).write_text(chart_html)
        print(f"wrote {blog_dir / name}")


